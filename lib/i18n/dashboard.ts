import type { AppLanguage } from "@/lib/app-language";
import type { SleepBandId } from "@/lib/analytics-psych";

export function sleepBandLabel(lang: AppLanguage, id: SleepBandId): string {
  const m: Record<AppLanguage, Record<SleepBandId, string>> = {
    en: {
      lt6: "< 6 h",
      "6-7": "6–7 h",
      "7-8": "7–8 h",
      gte8: "≥ 8 h",
    },
    ru: {
      lt6: "< 6 ч",
      "6-7": "6–7 ч",
      "7-8": "7–8 ч",
      gte8: "≥ 8 ч",
    },
  };
  return m[lang][id];
}

export function stressLevelLabel(lang: AppLanguage, level: string): string {
  const m: Record<AppLanguage, Record<string, string>> = {
    en: { low: "Low", medium: "Medium", high: "High" },
    ru: { low: "Низкий", medium: "Средний", high: "Высокий" },
  };
  return m[lang][level] ?? level;
}

